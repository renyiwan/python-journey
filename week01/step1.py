# ---- 变量（已写好，你读一遍就行）----
name = "恩溥"
major = "大数据管理与应用"
day = 1

# TODO 1：用 f-string 打印一句话，把上面三个变量拼进去
# 写法：字符串前面加 f，变量放在 {} 里
# 示例：print(f"我叫{name}")
# 你要输出的效果：我是恩溥，大数据管理与应用专业，今天是 Python 第 1 天
print(f"我叫{name},{major}专业,今天是学习python的第{day}天")


# ---- 输入 ----
# TODO 2：让用户输入一句英文，存进变量 sentence
# 写法：sentence = input("请输入一句英文：")
sentence = input("请输入一句英文：")


# ---- 切分 ----
# TODO 3：把这句话切成单词列表，打印「单词个数」
# 提示：words = sentence.split()   ← 按空格切成列表
# 提示：len(words)                 ← 列表长度
# 打印效果：这句话有 7 个单词

words=sentence.split()
print(f"这句话有{len(words)}个单词")
print(words[2])


# ---- 统计（这一步是今天的核心）----
# TODO 4：统计每个单词出现几次，存进字典 counts
# 遍历 words 里的每个词 w，往字典里累加。
# 新手最容易卡在这一行，直接给你：
#     counts[w] = counts.get(w, 0) + 1
# 意思是：这个词如果没出现过就当作 0，然后 +1
counts = {}          # ← 这行被误删了，补回来：先准备一个空本子
for w in words:
    counts[w] = counts.get(w, 0) + 1



# TODO 5：打印 counts，看看结果
# 试试多输入几个重复的词（比如 "hello world hello"），确认计数对不对
print(counts)

