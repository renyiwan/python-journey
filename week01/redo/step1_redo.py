# ---- 任务 1 ----
# 建三个变量：你的名字、你的专业、今天是第几天
# 然后用 f-string 打印成一句话：
#   我叫恩溥,大数据管理与应用专业,今天是学习python的第1天
name="任恩溥"
major="大数据管理与应用"
day=1
print(f"你好，我叫{name},专业是{major}今天是我学习python的第{day}天")

# ---- 任务 2 ----
# 让用户从键盘输入一句英文，把它存起来
sentence=input("输入一句英文")


# ---- 任务 3 ----
# 把这句话切成单词，打印出「这句话有X个单词」
words=sentence.split()
print(f"这句话有{len(words)}个单词")
print(words[0])

# ---- 任务 4（最难的一步）----
# 统计每个单词出现了几次，存进一个字典里
counts={}
for w in words :
    counts[w]=counts.get(w,0)+1


# ---- 任务 5 ----
# 把统计结果打印出来
print(counts)

